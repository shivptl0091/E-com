        // Theme Toggle
        function toggleTheme() {
            const html = document.documentElement;
            const currentTheme = html.getAttribute('data-theme');
            const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
            
            html.setAttribute('data-theme', newTheme);
            localStorage.setItem('theme', newTheme);
            
            // Toggle icons
            document.getElementById('sunIcon').classList.toggle('hidden');
            document.getElementById('moonIcon').classList.toggle('hidden');
        }

        // Load saved theme
        window.addEventListener('DOMContentLoaded', () => {
            const savedTheme = localStorage.getItem('theme') || 'light';
            document.documentElement.setAttribute('data-theme', savedTheme);
            
            if (savedTheme === 'dark') {
                document.getElementById('sunIcon').classList.add('hidden');
                document.getElementById('moonIcon').classList.remove('hidden');
            }
        });

        // Main Carousel
        let mainCurrentSlide = 0;
        const mainCarousel = {
            track: document.querySelector('#mainCarousel .carousel-track'),
            slides: document.querySelectorAll('#mainCarousel .carousel-slide'),
            indicators: document.querySelectorAll('#mainIndicators .carousel-indicator'),
            totalSlides: 3
        };

        function moveCarousel(carouselId, direction) {
            if (carouselId === 'main') {
                mainCurrentSlide += direction;
                
                if (mainCurrentSlide < 0) {
                    mainCurrentSlide = mainCarousel.totalSlides - 1;
                } else if (mainCurrentSlide >= mainCarousel.totalSlides) {
                    mainCurrentSlide = 0;
                }
                
                updateMainCarousel();
            }
        }

        function goToSlide(carouselId, index) {
            if (carouselId === 'main') {
                mainCurrentSlide = index;
                updateMainCarousel();
            }
        }

        function updateMainCarousel() {
            mainCarousel.track.style.transform = `translateX(-${mainCurrentSlide * 100}%)`;
            
            mainCarousel.indicators.forEach((indicator, index) => {
                if (index === mainCurrentSlide) {
                    indicator.classList.add('active');
                } else {
                    indicator.classList.remove('active');
                }
            });
        }

        // Auto-play main carousel
        let mainAutoPlay = setInterval(() => {
            moveCarousel('main', 1);
        }, 5000);

        // Pause on hover
        document.getElementById('mainCarousel').addEventListener('mouseenter', () => {
            clearInterval(mainAutoPlay);
        });

        document.getElementById('mainCarousel').addEventListener('mouseleave', () => {
            mainAutoPlay = setInterval(() => {
                moveCarousel('main', 1);
            }, 5000);
        });

        // Product Carousels
        const productCarousels = {};
        for (let i = 1; i <= 4; i++) {
            productCarousels[i] = {
                currentSlide: 0,
                track: document.querySelector(`#productCarousel${i}`),
                indicators: document.querySelectorAll(`#productCarousel${i}`).parentElement.querySelectorAll('.product-carousel-indicator'),
                totalSlides: 3
            };
        }

        function goToProductSlide(carouselNum, index) {
            const carousel = productCarousels[carouselNum];
            carousel.currentSlide = index;
            
            carousel.track.style.transform = `translateX(-${index * 100}%)`;
            
            const indicators = carousel.track.parentElement.querySelectorAll('.product-carousel-indicator');
            indicators.forEach((indicator, i) => {
                if (i === index) {
                    indicator.classList.add('active');
                } else {
                    indicator.classList.remove('active');
                }
            });
        }

        // Auto-play product carousels
        Object.keys(productCarousels).forEach(carouselNum => {
            let autoPlay = setInterval(() => {
                const carousel = productCarousels[carouselNum];
                carousel.currentSlide = (carousel.currentSlide + 1) % carousel.totalSlides;
                goToProductSlide(carouselNum, carousel.currentSlide);
            }, 4000 + (carouselNum * 500)); // Stagger the timing

            // Pause on hover
            const carouselElement = document.querySelector(`#productCarousel${carouselNum}`).parentElement;
            carouselElement.addEventListener('mouseenter', () => {
                clearInterval(autoPlay);
            });

            carouselElement.addEventListener('mouseleave', () => {
                autoPlay = setInterval(() => {
                    const carousel = productCarousels[carouselNum];
                    carousel.currentSlide = (carousel.currentSlide + 1) % carousel.totalSlides;
                    goToProductSlide(carouselNum, carousel.currentSlide);
                }, 4000 + (carouselNum * 500));
            });
        });

        // Mobile Menu Toggle
        function toggleMobileMenu() {
            const menu = document.getElementById('mobileMenu');
            const overlay = document.getElementById('mobileMenuOverlay');
            
            menu.classList.toggle('active');
            overlay.classList.toggle('active');
        }

        // Search Toggle
        function toggleSearch() {
            const searchBar = document.getElementById('searchBar');
            searchBar.classList.toggle('hidden');
            
            if (!searchBar.classList.contains('hidden')) {
                searchBar.querySelector('input').focus();
            }
        }

        // Navbar scroll effect
